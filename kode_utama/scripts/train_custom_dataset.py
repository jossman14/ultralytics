#!/usr/bin/env python3
"""
Script Training Sederhana untuk Dataset Baru
=============================================

Panduan penggunaan:
1. Siapkan dataset dengan struktur:
   dataset_baru/
   ├── train/images/
   ├── train/labels/
   ├── valid/images/
   └── valid/labels/

2. Buat file dataset_baru.yaml (lihat contoh di konfigurasi/dataset_template.yaml)

3. Jalankan script ini:
   python train_custom_dataset.py --data /path/to/dataset_baru.yaml --model yolov8s

Author: Generated by AI
Date: 2025
"""

import os
import sys
import argparse
import yaml
from pathlib import Path
from datetime import datetime

# Pastikan ultralytics tersedia
sys.path.insert(0, str(Path(__file__).parent.parent / "original"))

try:
    from ultralytics import YOLO
except ImportError:
    print("Error: ultralytics tidak terinstall!")
    print("Install dengan: pip install ultralytics")
    sys.exit(1)


def create_dataset_yaml(dataset_path: str, num_classes: int, class_names: list):
    """
    Membuat file YAML untuk dataset baru.
    
    Args:
        dataset_path: Path ke root dataset
        num_classes: Jumlah kelas
        class_names: List nama kelas
    """
    dataset_path = Path(dataset_path)
    
    # Pastikan struktur folder benar
    for split in ["train", "valid", "test"]:
        (dataset_path / split / "images").mkdir(parents=True, exist_ok=True)
        (dataset_path / split / "labels").mkdir(parents=True, exist_ok=True)
    
    # Buat YAML config
    config = {
        "path": str(dataset_path.absolute()),
        "train": "train/images",
        "val": "valid/images",
        "test": "test/images",
        "names": {i: name for i, name in enumerate(class_names)}
    }
    
    yaml_path = dataset_path / "dataset_config.yaml"
    with open(yaml_path, "w") as f:
        yaml.dump(config, f, default_flow_style=False, sort_keys=False)
    
    print(f"✓ File konfigurasi dibuat: {yaml_path}")
    return str(yaml_path)


def validate_dataset(data_yaml: str):
    """
    Validasi struktur dataset.
    
    Args:
        data_yaml: Path ke file YAML dataset
    """
    with open(data_yaml, "r") as f:
        config = yaml.safe_load(f)
    
    dataset_path = Path(config["path"])
    
    # Check folder
    required_folders = [
        Path(config["train"]),
        Path(config["val"])
    ]
    
    for folder in required_folders:
        full_path = dataset_path / folder
        if not full_path.exists():
            print(f"❌ Folder tidak ditemukan: {full_path}")
            return False
        
        # Check images
        images = list(full_path.glob("*"))
        if len(images) == 0:
            print(f"⚠️  Tidak ada gambar di: {full_path}")
        else:
            print(f"✓ {full_path}: {len(images)} gambar")
    
    # Check class names
    num_classes = len(config.get("names", {}))
    print(f"✓ Dataset memiliki {num_classes} kelas")
    
    return True


def train_model(
    data_yaml: str,
    model_type: str = "yolov8s",
    epochs: int = 100,
    batch_size: int = 16,
    img_size: int = 480,
    device: str = "0",
    patience: int = 30,
    output_dir: str = None
):
    """
    Training model YOLO.
    
    Args:
        data_yaml: Path ke file YAML dataset
        model_type: Tipe model (yolov8n, yolov8s, yolov8m, yolov8l, yolov8x)
        epochs: Jumlah epoch
        batch_size: Ukuran batch
        img_size: Ukuran gambar
        device: GPU device ("0", "0,1", "cpu")
        patience: Early stopping patience
        output_dir: Direktori output (optional)
    """
    print("=" * 60)
    print("🚀 Memulai Training")
    print("=" * 60)
    print(f"📊 Dataset: {data_yaml}")
    print(f"🤖 Model: {model_type}")
    print(f"📈 Epochs: {epochs}")
    print(f"📦 Batch Size: {batch_size}")
    print(f"🖼️  Image Size: {img_size}")
    print(f"⚙️  Device: {device}")
    print("=" * 60)
    
    # Load pretrained model
    model = YOLO(f"{model_type}.pt")
    
    # Training
    results = model.train(
        data=data_yaml,
        epochs=epochs,
        imgsz=img_size,
        batch=batch_size,
        device=device,
        patience=patience,
        optimizer="AdamW",
        cos_lr=True,
        close_mosaic=10,
        project=output_dir or "runs/detect",
        name=f"train_{datetime.now().strftime('%Y%m%d_%H%M%S')}",
        exist_ok=False
    )
    
    print("\n" + "=" * 60)
    print("✅ Training Selesai!")
    print("=" * 60)
    print(f"📁 Hasil tersimpan di: {results.save_dir}")
    print(f"🏆 Best weights: {results.best}")
    print(f"📊 mAP50: {results.results_dict.get('metrics/mAP50(B)', 0):.4f}")
    print(f"📊 mAP50-95: {results.results_dict.get('metrics/mAP50-95(B)', 0):.4f}")
    
    return results


def evaluate_model(weights_path: str, data_yaml: str):
    """
    Evaluasi model yang telah dilatih.
    
    Args:
        weights_path: Path ke file weights (.pt)
        data_yaml: Path ke file YAML dataset
    """
    print("\n" + "=" * 60)
    print("🔍 Evaluasi Model")
    print("=" * 60)
    
    model = YOLO(weights_path)
    metrics = model.val(data=data_yaml)
    
    print(f"📊 mAP50: {metrics.box.map50:.4f}")
    print(f"📊 mAP50-95: {metrics.box.map:.4f}")
    print(f"📊 Precision: {metrics.box.p:.4f}")
    print(f"📊 Recall: {metrics.box.r:.4f}")
    
    return metrics


def predict_image(weights_path: str, image_path: str):
    """
    Prediksi pada gambar.
    
    Args:
        weights_path: Path ke file weights (.pt)
        image_path: Path ke gambar
    """
    print(f"\n🖼️  Prediksi pada: {image_path}")
    
    model = YOLO(weights_path)
    results = model(image_path, save=True)
    
    for result in results:
        print(f"  📦 Deteksi: {len(result.boxes)} objek")
        for box in result.boxes:
            cls_id = int(box.cls)
            conf = float(box.conf)
            print(f"    - Kelas {cls_id}: {conf:.2f}")
    
    return results


def main():
    parser = argparse.ArgumentParser(
        description="Training YOLO pada Dataset Baru",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Contoh penggunaan:
  # Training dasar:
  python train_custom_dataset.py --data /path/to/data.yaml
  
  # Training dengan model custom:
  python train_custom_dataset.py --data /path/to/data.yaml --model yolov8m
  
  # Training dengan parameter custom:
  python train_custom_dataset.py --data /path/to/data.yaml --epochs 200 --batch 32
  
  # Evaluasi model:
  python train_custom_dataset.py --eval --weights runs/detect/train/weights/best.pt --data /path/to/data.yaml
  
  # Prediksi:
  python train_custom_dataset.py --predict --weights best.pt --image test.jpg
        """
    )
    
    # Dataset args
    parser.add_argument("--data", type=str, help="Path ke file YAML dataset")
    parser.add_argument("--create-dataset", type=str, help="Buat struktur dataset baru")
    parser.add_argument("--num-classes", type=int, default=1, help="Jumlah kelas")
    parser.add_argument("--class-names", nargs="+", default=["object"], help="Nama kelas")
    
    # Training args
    parser.add_argument("--train", action="store_true", help="Jalankan training")
    parser.add_argument("--model", type=str, default="yolov8s", 
                        choices=["yolov8n", "yolov8s", "yolov8m", "yolov8l", "yolov8x"],
                        help="Tipe model YOLOv8")
    parser.add_argument("--epochs", type=int, default=100, help="Jumlah epoch")
    parser.add_argument("--batch", type=int, default=16, help="Batch size")
    parser.add_argument("--imgsz", type=int, default=480, help="Ukuran gambar")
    parser.add_argument("--device", type=str, default="0", help="Device (0, 0,1, cpu)")
    parser.add_argument("--patience", type=int, default=30, help="Early stopping patience")
    parser.add_argument("--output", type=str, help="Direktori output")
    
    # Evaluation args
    parser.add_argument("--eval", action="store_true", help="Evaluasi model")
    parser.add_argument("--weights", type=str, help="Path ke weights model")
    
    # Prediction args
    parser.add_argument("--predict", action="store_true", help="Prediksi pada gambar")
    parser.add_argument("--image", type=str, help="Path ke gambar untuk prediksi")
    
    # Other args
    parser.add_argument("--validate", action="store_true", help="Validasi dataset tanpa training")
    
    args = parser.parse_args()
    
    # Buat dataset baru
    if args.create_dataset:
        yaml_path = create_dataset_yaml(
            args.create_dataset,
            args.num_classes,
            args.class_names
        )
        print("\n✅ Struktur dataset berhasil dibuat!")
        print(f"   Path: {args.create_dataset}")
        print(f"   Config: {yaml_path}")
        print("\n   Langkah selanjutnya:")
        print("   1. Letakkan gambar training di train/images/")
        print("   2. Letakkan label di train/labels/ (format YOLO)")
        print("   3. Letakkan gambar validation di valid/images/")
        print("   4. Letakkan label validation di valid/labels/")
        print(f"   5. Jalankan: python {__file__} --data {yaml_path} --train")
        return
    
    # Validasi dataset
    if args.validate and args.data:
        if validate_dataset(args.data):
            print("\n✅ Dataset valid!")
        else:
            print("\n❌ Dataset tidak valid!")
        return
    
    # Training
    if args.train or (args.data and not args.eval and not args.predict):
        if not args.data:
            print("❌ Error: --data wajib diisi!")
            return
        
        # Validasi dulu
        if not validate_dataset(args.data):
            print("❌ Dataset tidak valid. Periksa struktur folder.")
            return
        
        # Training
        results = train_model(
            data_yaml=args.data,
            model_type=args.model,
            epochs=args.epochs,
            batch_size=args.batch,
            img_size=args.imgsz,
            device=args.device,
            patience=args.patience,
            output_dir=args.output
        )
        
        # Auto evaluasi
        best_weights = Path(results.save_dir) / "weights" / "best.pt"
        if best_weights.exists():
            evaluate_model(str(best_weights), args.data)
    
    # Evaluasi
    if args.eval:
        if not args.weights or not args.data:
            print("❌ Error: --weights dan --data wajib diisi untuk evaluasi!")
            return
        evaluate_model(args.weights, args.data)
    
    # Prediksi
    if args.predict:
        if not args.weights or not args.image:
            print("❌ Error: --weights dan --image wajib diisi untuk prediksi!")
            return
        predict_image(args.weights, args.image)


if __name__ == "__main__":
    main()
